using Microsoft.AspNetCore.Mvc;
using System;
using System.Collections.Generic;
using System.Linq;

namespace Security.AccessTokenHandling.OAuth.Server {

  internal partial class OAuth2Controller {

    ///////////////////////////////////////////////////////////////////////////////////////////////////
    // PROMPT (OIDC Core 3.1.2.1) - optional 'prompt' param ('none' / 'login' / 'consent' / ...)     //
    // + SKIPPING OF THE CONSENT STEP, IF THERE IS NOTHING TO SELECT                                 //
    ///////////////////////////////////////////////////////////////////////////////////////////////////

    /// <summary>
    /// Name of the hidden form field, which is used to pass the 'prompt' param trough the html forms
    /// (not 'prompt', because the auth page builders already use this term for the displayed text).
    /// </summary>
    private const string _PromptFormFieldName = "oauthPrompt";

    /// <summary>
    /// Returns true, if the space separated 'prompt' param contains the specified value (case insensitive).
    /// </summary>
    internal static bool HasPromptValue(string prompt, string value) {
      if (string.IsNullOrWhiteSpace(prompt)) {
        return false;
      }
      string[] values = prompt.Split(new char[] { ' ' }, StringSplitOptions.RemoveEmptyEntries);
      foreach (string currentValue in values) {
        if (string.Equals(currentValue, value, StringComparison.OrdinalIgnoreCase)) {
          return true;
        }
      }
      return false;
    }

    /// <summary>
    /// Validates the 'prompt' param: 'none' must not be combined with any other value.
    /// Unknown values are tolerated (backward compatibility).
    /// </summary>
    internal static bool TryValidatePromptParam(string prompt, out string errorDescription) {
      if (HasPromptValue(prompt, "none")) {
        string[] values = prompt.Split(new char[] { ' ' }, StringSplitOptions.RemoveEmptyEntries);
        if (values.Length > 1) {
          errorDescription = "The 'prompt' value 'none' must not be combined with other values.";
          return false;
        }
      }
      errorDescription = null;
      return true;
    }

    /// <summary>
    /// Injects the 'prompt' param as hidden field into a html form (generated by the IAuthPageBuilder).
    /// Returns false, if the form could not be found (in this case the prompt would get lost).
    /// </summary>
    internal static bool TryInjectPromptFormField(ref string formHtml, string prompt) {
      if (string.IsNullOrEmpty(prompt)) {
        return true;
      }
      int formEndIndex = formHtml.IndexOf("</form>", StringComparison.OrdinalIgnoreCase);
      if (formEndIndex < 0) {
        return false;
      }
      string hiddenField = $"<input type=\"hidden\" id=\"{_PromptFormFieldName}\" name=\"{_PromptFormFieldName}\" value=\"{System.Web.HttpUtility.HtmlAttributeEncode(prompt)}\">";
      formHtml = formHtml.Insert(formEndIndex, hiddenField);
      return true;
    }

    /// <summary>
    /// Appends the 'prompt' query param to an (internal) './authorize' url.
    /// </summary>
    internal static string AppendPromptQueryParam(string authorizeUrl, string prompt) {
      if (string.IsNullOrEmpty(prompt)) {
        return authorizeUrl;
      }
      return authorizeUrl.AppendQueryParam("prompt", prompt, true);
    }

    /// <summary>
    /// Appends the PKCE query params, the 'resource' and the 'prompt' query param to an (internal) './authorize' url.
    /// </summary>
    internal static string AppendRoundtripQueryParams(string authorizeUrl, string codeChallenge, string resource, string prompt) {
      return AppendPromptQueryParam(AppendRoundtripQueryParams(authorizeUrl, codeChallenge, resource), prompt);
    }

    /// <summary>
    /// Evaluates, whether the consent step can be skipped, because the user has nothing to select
    /// (no visible scope, which is not read-only). In this case the scopes, which would have been
    /// posted by the consent form, are returned.
    /// </summary>
    internal static bool TryGetScopesWithoutSelection(ScopeDescriptor[] availableScopes, out string[] selectedScopes) {
      List<string> result = new List<string>();
      if (availableScopes != null) {
        foreach (ScopeDescriptor scope in availableScopes.Where((s) => !s.Invisible)) {
          if (!scope.ReadOnly) {
            selectedScopes = null;
            return false;
          }
          if (scope.Selected) {
            result.Add(scope.Expression);
          }
        }
      }
      selectedScopes = result.ToArray();
      return true;
    }

    /// <summary>
    /// Builds an error redirect to the client (or an error page for response type 'display').
    /// </summary>
    private ActionResult CreateClientErrorResult(
      string responseType, string redirectUri, string state, string error, string errorDescription, AuthPageViewModeOptions viewOpt
    ) {
      if (string.Equals(responseType, "display", StringComparison.InvariantCultureIgnoreCase) || string.IsNullOrWhiteSpace(redirectUri)) {
        string errorPage = _AuthPageBuilder.GetErrorPage(error + ": " + errorDescription, viewOpt);
        return this.Content(errorPage, "text/html");
      }
      string target = redirectUri.AppendQueryParam("error", error).AppendQueryParam("error_description", errorDescription, true);
      if (!string.IsNullOrWhiteSpace(state)) {
        target = target.AppendQueryParam("state", state, true);
      }
      return this.Redirect(target);
    }

    /// <summary>
    /// Issues the result of the authorization (code / token / display) for an authenticated session
    /// and the finally granted scopes. Returns null, if the code creation failed (in this case
    /// 'failureMessage' is set and the caller decides how to handle it).
    /// </summary>
    private ActionResult IssueAuthorizationResult(
      string responseType, string clientId, string sessionId, string[] selectedScopes, string redirectUri, string state,
      string codeChallenge, string resource, AuthPageViewModeOptions viewOpt, out string failureMessage
    ) {
      failureMessage = null;

      if (responseType.Equals("code", StringComparison.InvariantCultureIgnoreCase)) {

        bool success = _AuthService.TryValidateSessionIdAndCreateRetrievalCode(
          clientId, sessionId, selectedScopes, codeChallenge, resource, out string code, out string step2Msg
        );

        if (!success || string.IsNullOrWhiteSpace(code)) {
          failureMessage = step2Msg;
          if (string.IsNullOrWhiteSpace(failureMessage)) {
            failureMessage = "No code could be created.";
          }
          return null;
        }

        redirectUri = AppendUrlParam(redirectUri, "code", code, false);
      }
      else if (responseType.Equals("token", StringComparison.InvariantCultureIgnoreCase)) {

        TokenIssuingResult tokenResult = null;
        if (_AuthService.TryValidateSessionIdAndCreateToken(clientId, sessionId, selectedScopes, out tokenResult)) {
          redirectUri = AppendUrlParam(redirectUri, tokenResult.ToString());
        }
        else {
          if (tokenResult != null && !string.IsNullOrWhiteSpace(tokenResult.error)) {
            redirectUri = AppendUrlParam(redirectUri, "error", tokenResult.error, true);
          }
          else {
            redirectUri = AppendUrlParam(redirectUri, "error", "no-token", false);
          }
        }
      }
      else if (responseType.Equals("display", StringComparison.InvariantCultureIgnoreCase)) {
        if (_AuthService.TryValidateSessionIdAndCreateToken(clientId, sessionId, selectedScopes, out TokenIssuingResult result)) {
          string displayPage = _AuthPageBuilder.GetTokenDisplayPage(result, viewOpt);
          return this.Content(displayPage, "text/html");
        }
        else {
          string errorPage = _AuthPageBuilder.GetErrorPage("Got no Token to display...", viewOpt);
          return this.Content(errorPage, "text/html");
        }
      }
      else {
        redirectUri = AppendUrlParam(redirectUri, "error", "unknown-response-type", false);
      }

      if (!string.IsNullOrWhiteSpace(state)) {
        redirectUri = AppendUrlParam(redirectUri, "state", state, false);
      }
      return this.Redirect(redirectUri);
    }

  }

}
