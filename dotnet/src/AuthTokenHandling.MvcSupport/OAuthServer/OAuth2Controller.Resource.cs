using System;

namespace Security.AccessTokenHandling.OAuth.Server {

  internal partial class OAuth2Controller {

    ///////////////////////////////////////////////////////////////////////////////////////////////////
    // RESOURCE INDICATORS (RFC 8707) - the 'resource' param is optional and carried trough opaque   //
    ///////////////////////////////////////////////////////////////////////////////////////////////////

    /// <summary>
    /// Name of the hidden form field, which is used to pass the resource indicator trough the html forms.
    /// </summary>
    private const string _ResourceFormFieldName = "resource";

    /// <summary>
    /// Validates the 'resource' param of an incoming authorize request (RFC 8707, section 2):
    /// it must be an absolute URI without fragment. Returns true if no resource was requested.
    /// </summary>
    /// <param name="resource">the 'resource' param (can be null/empty)</param>
    /// <param name="errorDescription">null, if valid</param>
    internal static bool TryValidateResourceParam(string resource, out string errorDescription) {
      if (string.IsNullOrEmpty(resource)) {
        errorDescription = null;
        return true;
      }
      Uri parsedResource;
      if (!Uri.TryCreate(resource, UriKind.Absolute, out parsedResource)) {
        errorDescription = "The 'resource' must be an absolute URI.";
        return false;
      }
      if (resource.IndexOf('#') >= 0) {
        errorDescription = "The 'resource' must not contain a fragment.";
        return false;
      }
      errorDescription = null;
      return true;
    }

    /// <summary>
    /// Injects the resource indicator as hidden field into a html form (generated by the IAuthPageBuilder).
    /// Returns false, if the form could not be found (in this case the resource would get lost).
    /// </summary>
    internal static bool TryInjectResourceFormField(ref string formHtml, string resource) {
      if (string.IsNullOrEmpty(resource)) {
        return true;
      }
      int formEndIndex = formHtml.IndexOf("</form>", StringComparison.OrdinalIgnoreCase);
      if (formEndIndex < 0) {
        return false;
      }
      string hiddenField = $"<input type=\"hidden\" id=\"{_ResourceFormFieldName}\" name=\"{_ResourceFormFieldName}\" value=\"{System.Web.HttpUtility.HtmlAttributeEncode(resource)}\">";
      formHtml = formHtml.Insert(formEndIndex, hiddenField);
      return true;
    }

    /// <summary>
    /// Appends the 'resource' query param to an (internal) './authorize' url, so that the resource indicator
    /// will not get lost when redirecting back to the authorize page.
    /// </summary>
    internal static string AppendResourceQueryParam(string authorizeUrl, string resource) {
      if (string.IsNullOrEmpty(resource)) {
        return authorizeUrl;
      }
      return authorizeUrl.AppendQueryParam("resource", resource, true);
    }

    /// <summary>
    /// Appends the PKCE query params and the 'resource' query param to an (internal) './authorize' url.
    /// </summary>
    internal static string AppendRoundtripQueryParams(string authorizeUrl, string codeChallenge, string resource) {
      return AppendResourceQueryParam(AppendPkceQueryParams(authorizeUrl, codeChallenge), resource);
    }

  }

}
